// Описывает, как экран запрашивает историю и сохраняет изменения. По одному договору работают
// местное хранилище и хранилище с обменом через сервер.

import Foundation
protocol ChatRepository: Sendable {
  // Помечает непрочитанные сообщения чата прочитанными, чтобы счётчик в списке исчез после
  // просмотра.
  func markRead(chatID: ChatID) async throws
  // Возвращает краткие сведения о чатах с учётом строки поиска. По ним экран строит список и
  // показывает последнюю активность.
  func chats(matching query: String) async throws -> [ChatSummary]
  // Читает ограниченную порцию сообщений вокруг нужного места. Так экран может показать часть
  // большой истории без чтения всех сообщений сразу.
  func history(_ request: PageRequest) async throws -> HistoryPage
  // Возвращает упорядоченные номера и краткие признаки строк. Они нужны для прокрутки и поиска
  // позиции без загрузки содержимого всего чата.
  func index(chatID: ChatID) async throws -> [IndexedRow]
  // Применяет команду отправки и возвращает изменения для экрана. Команда несёт свой номер, по
  // которому хранилище может распознать повтор.
  func send(_ command: SendCommand) async throws -> MessageDelta
  // Удаляет выбранное сообщение и возвращает изменения, по которым экран уберёт именно эту
  // строку.
  func delete(messageID: MessageID) async throws -> MessageDelta
  // Ищет сообщения в одном чате и при продолжении ограничивает поиск более ранней позицией. Иначе
  // следующая порция повторит уже показанные совпадения.
  func search(chatID: ChatID, text: String, before: OrderKey?) async throws -> [MessageID]
  // Записывает черновик выбранного чата, чтобы текст и вложения можно было вернуть после закрытия
  // экрана.
  func saveDraft(chatID: ChatID, draft: Draft) async throws
  // Восстанавливает черновик вместе со сведениями о начатой отправке. Без этих сведений
  // пользователь потеряет ввод или продолжение незавершённого действия.
  func draft(chatID: ChatID) async throws -> Draft
  // Запоминает строку под точкой чтения, смещение внутри неё и связь с концом истории. Без этой
  // записи чат при возврате открылся бы в другом месте.
  func savePosition(chatID: ChatID, anchor: ReadingAnchor) async throws
  // Читает сохранённую точку чтения. Отсутствие записи позволяет экрану выбрать начальную позицию
  // по правилам первого открытия.
  func position(chatID: ChatID) async throws -> ReadingAnchor?
}
